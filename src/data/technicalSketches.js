const SKETCH_KINDS = new Set([
  'circuit',
  'timing',
  'memory',
  'process',
  'object-lifetime',
  'data-structure',
]);

const nonEmptyText = (value) => typeof value === 'string' && value.trim().length > 0;

export function defineTechnicalSketch(spec) {
  for (const key of ['id', 'title', 'question', 'description', 'textEquivalent']) {
    if (!nonEmptyText(spec?.[key])) {
      throw new TypeError(`${spec?.id ?? 'sketch'}: ${key}`);
    }
  }

  if (!SKETCH_KINDS.has(spec.kind)) {
    throw new TypeError(`${spec.id}: kind`);
  }

  if (spec.interactive) {
    if (!Array.isArray(spec.steps) || spec.steps.length < 2) {
      throw new TypeError(`${spec.id}: steps`);
    }
    for (const step of spec.steps) {
      for (const key of ['id', 'action', 'reason', 'invariant', 'result']) {
        if (!nonEmptyText(step?.[key])) {
          throw new TypeError(`${spec.id}: steps:${key}`);
        }
      }
    }
  }

  return Object.freeze(spec);
}

