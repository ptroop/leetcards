    correctness: 'Every subarray ending at i either contains only a[i], or is a subarray ending at i-1 followed by a[i]. Among the second group, extending the best previous ending is optimal. Taking the maximum of those exhaustive cases proves the recurrence; taking the maximum over endpoints proves the final answer.',
